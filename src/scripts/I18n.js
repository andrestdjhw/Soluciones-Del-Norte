function applyOne(node, lang) {
  const table = dict[lang] || dict.es

  const textKey = node.getAttribute("data-i18n")
  if (textKey && table[textKey] != null) node.innerHTML = table[textKey]

  const hrefKey = node.getAttribute("data-i18n-href")
  if (hrefKey && table[hrefKey] != null) node.setAttribute("href", table[hrefKey])

  const altKey = node.getAttribute("data-i18n-alt")
  if (altKey && table[altKey] != null) node.setAttribute("alt", table[altKey])

  const titleKey = node.getAttribute("data-i18n-title")
  if (titleKey && table[titleKey] != null) node.setAttribute("title", table[titleKey])

  const ariaLabelKey = node.getAttribute("data-i18n-aria-label")
  if (ariaLabelKey && table[ariaLabelKey] != null) node.setAttribute("aria-label", table[ariaLabelKey])
}

export function applyLang(lang) {
  const nodes = document.querySelectorAll(
    "[data-i18n], [data-i18n-href], [data-i18n-alt], [data-i18n-title], [data-i18n-aria-label]"
  )
  nodes.forEach((node) => applyOne(node, lang))
}

export function initI18n() {
  // #sdn-navbar ya trae `data-lang` con el idioma que renderizó
  // PHP para esta ruta (header.php lo pone en todas las páginas) —
  // no hace falta un atributo nuevo solo para esto.
  const navbar = document.getElementById("sdn-navbar")
  const serverLang = navbar ? navbar.getAttribute("data-lang") : "es"
  const initial = getStoredLang(serverLang)

  applyLang(initial)
  document.documentElement.lang = initial

  window.addEventListener(LANG_EVENT, (e) => applyLang(e.detail))
}

